import React, { useCallback, useEffect, useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import Sidebar from '../components/Sidebar';
import MapView from '../components/MapView';
import FareTaxStatus from '../components/FareTaxStatus';
import RideStatus, { formatRideDate } from '../components/RideStatus';
import Loading from '../components/Loading';
import Notifications from '../components/Notifications';
import Instructions from '../components/Instructions';

const LOCATIONS = ['Estancia', 'Poblacion, Kalibo', 'Mabilo', 'New Buswang', 'Mobo', 'Pook'];
const ACTIVE_STATUSES = ['Pending', 'Accepted', 'Assigned', 'In Progress'];
const ALL_STATUSES = ['Pending', 'Accepted', 'Assigned', 'In Progress', 'Completed', 'Cancelled'];

const pageTitles = {
  dashboard: ['Passenger dashboard', 'Your Kalibo rides at a glance.'],
  book: ['Book a tricycle', 'Choose a route, review the estimate, and request a ride.'],
  rides: ['My rides', 'Follow your current ride and review saved history.'],
  notifications: ['Notifications', 'Updates generated by your account activity.'],
  admin: ['Administrator overview', 'Monitor actual local application activity.'],
  requests: ['Ride requests', 'Assign tricycles and manage every ride status.'],
  passengers: ['Registered passengers', 'Passenger accounts and their ride activity.'],
  tricycles: ['Tricycle records', 'Simulated local availability for school demonstrations.'],
};

function Home({ apiRequest, user }) {
  const isAdmin = user.role === 'admin';
  const navigate = useNavigate();
  const [activePage, setActivePage] = useState(isAdmin ? 'admin' : 'dashboard');
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');
  const [rides, setRides] = useState([]);
  const [notifications, setNotifications] = useState([]);
  const [availability, setAvailability] = useState({ available: 0 });
  const [booking, setBooking] = useState({ pickup: 'Poblacion, Kalibo', destination: 'Mabilo' });
  const [quote, setQuote] = useState(null);
  const [quoteLoading, setQuoteLoading] = useState(false);
  const [actionLoading, setActionLoading] = useState('');
  const [stats, setStats] = useState(null);
  const [passengers, setPassengers] = useState([]);
  const [tricycles, setTricycles] = useState([]);
  const [adminRides, setAdminRides] = useState([]);
  const [statusFilter, setStatusFilter] = useState('');
  const [adminForms, setAdminForms] = useState({});

  const loadData = useCallback(async (showLoader = true) => {
    if (showLoader) setLoading(true);
    setError('');
    try {
      if (isAdmin) {
        const [statsData, passengerData, tricycleData, rideData] = await Promise.all([
          apiRequest('/admin/stats'),
          apiRequest('/admin/passengers'),
          apiRequest('/admin/tricycles'),
          apiRequest('/admin/rides'),
        ]);
        setStats(statsData);
        setPassengers(passengerData);
        setTricycles(tricycleData);
        setAdminRides(rideData);
      } else {
        const [rideData, notificationData, availabilityData] = await Promise.all([
          apiRequest('/rides/mine'),
          apiRequest('/notifications'),
          apiRequest('/tricycles/availability'),
        ]);
        setRides(rideData);
        setNotifications(notificationData);
        setAvailability(availabilityData);
      }
    } catch (requestError) {
      setError(requestError.message || 'Unable to load data. Make sure ngilo-api is running.');
    } finally {
      setLoading(false);
    }
  }, [apiRequest, isAdmin]);

  useEffect(() => {
    loadData();
  }, [loadData]);

  useEffect(() => {
    if (isAdmin || activePage !== 'book' || booking.pickup === booking.destination) {
      setQuote(null);
      return undefined;
    }
    let ignore = false;
    setQuoteLoading(true);
    apiRequest(`/fare?pickup=${encodeURIComponent(booking.pickup)}&destination=${encodeURIComponent(booking.destination)}`)
      .then((data) => { if (!ignore) setQuote(data); })
      .catch((requestError) => { if (!ignore) setError(requestError.message); })
      .finally(() => { if (!ignore) setQuoteLoading(false); });
    return () => { ignore = true; };
  }, [activePage, booking, apiRequest, isAdmin]);

  const currentRide = rides.find((ride) => ACTIVE_STATUSES.includes(ride.status));
  const unreadCount = notifications.filter((item) => !item.is_read).length;
  const filteredAdminRides = useMemo(
    () => statusFilter ? adminRides.filter((ride) => ride.status === statusFilter) : adminRides,
    [adminRides, statusFilter],
  );
  const [pageTitle, pageSubtitle] = pageTitles[activePage] || pageTitles.dashboard;

  const handleNavigate = (page) => {
    if (page === 'profile') {
      navigate('/profile');
      return;
    }
    setActivePage(page);
    setSidebarOpen(false);
    setNotice('');
    setError('');
  };

  const handleLogout = async () => {
    try {
      await apiRequest('/logout', { method: 'POST' });
    } catch {
      // Local sign-out still proceeds if the API is already offline.
    } finally {
      localStorage.removeItem('user');
      navigate('/');
    }
  };

  const handleBook = async (event) => {
    event.preventDefault();
    if (!quote || currentRide) return;
    setActionLoading('book');
    setError('');
    try {
      await apiRequest('/rides', { method: 'POST', body: booking });
      await loadData(false);
      setNotice('Ride request saved. Your assignment and status are now available in My rides.');
      setActivePage('rides');
    } catch (requestError) {
      setError(requestError.message);
    } finally {
      setActionLoading('');
    }
  };

  const handleCancel = async (rideId) => {
    setActionLoading(`cancel-${rideId}`);
    setError('');
    try {
      await apiRequest(`/rides/${rideId}/cancel`, { method: 'PATCH' });
      await loadData(false);
      setNotice('Ride cancelled. The tricycle is available again.');
    } catch (requestError) {
      setError(requestError.message);
    } finally {
      setActionLoading('');
    }
  };

  const handlePay = async (rideId) => {
    setActionLoading(`pay-${rideId}`);
    setError('');
    try {
      await apiRequest(`/rides/${rideId}/pay`, { method: 'PATCH' });
      await loadData(false);
      setNotice('Simulated payment recorded. No real money was transferred.');
    } catch (requestError) {
      setError(requestError.message);
    } finally {
      setActionLoading('');
    }
  };

  const handleRead = async (id) => {
    try {
      await apiRequest(`/notifications/${id}/read`, { method: 'PATCH' });
      setNotifications((items) => items.map((item) => item.id === id ? { ...item, is_read: 1 } : item));
    } catch (requestError) {
      setError(requestError.message);
    }
  };

  const handleReadAll = async () => {
    try {
      await apiRequest('/notifications/read-all', { method: 'PATCH' });
      setNotifications((items) => items.map((item) => ({ ...item, is_read: 1 })));
    } catch (requestError) {
      setError(requestError.message);
    }
  };

  const updateAdminForm = (rideId, field, value) => {
    setAdminForms((forms) => ({
      ...forms,
      [rideId]: { ...forms[rideId], [field]: value },
    }));
  };

  const handleAdminUpdate = async (event, ride) => {
    event.preventDefault();
    const form = adminForms[ride.ride_id] || {};
    const status = form.status || ride.status;
    const tricycleId = form.tricycleId || ride.tricycle_id || '';
    setActionLoading(`admin-${ride.ride_id}`);
    setError('');
    try {
      await apiRequest(`/admin/rides/${ride.ride_id}`, {
        method: 'PATCH',
        body: { status, tricycleId: tricycleId || null },
      });
      await loadData(false);
      setNotice(`Ride #${ride.ride_id.slice(0, 8).toUpperCase()} updated to ${status}.`);
    } catch (requestError) {
      setError(requestError.message);
    } finally {
      setActionLoading('');
    }
  };

  const passengerDashboard = () => (
    <>
      <section className="welcome-banner">
        <div>
          <span className="eyebrow">SAKAY NA, {user.fullName?.split(' ')[0]?.toUpperCase()}!</span>
          <h2>Where are you going today?</h2>
          <p>Request a tricycle and follow every saved status from pickup to completion.</p>
          <button className="btn btn-gold" type="button" onClick={() => handleNavigate('book')}>
            <i className="bi bi-plus-lg" /> Book a tricycle
          </button>
        </div>
        <div className="welcome-illustration" aria-hidden="true">
          <i className="bi bi-truck-front" />
          <span>KALIBO</span>
        </div>
      </section>

      <section className="stat-grid passenger-stats">
        <button type="button" className="stat-card" onClick={() => handleNavigate('rides')}>
          <span className="stat-icon gold"><i className="bi bi-signpost-2" /></span>
          <div><strong>{rides.length}</strong><span>Total ride requests</span></div>
          <i className="bi bi-arrow-up-right" />
        </button>
        <button type="button" className="stat-card" onClick={() => handleNavigate('rides')}>
          <span className="stat-icon green"><i className="bi bi-clock-history" /></span>
          <div><strong>{currentRide ? 1 : 0}</strong><span>Current active ride</span></div>
          <i className="bi bi-arrow-up-right" />
        </button>
        <div className="stat-card">
          <span className="stat-icon navy"><i className="bi bi-truck-front" /></span>
          <div><strong>{availability.available}</strong><span>Tricycles available</span></div>
          <small>Simulated</small>
        </div>
      </section>

      <div className="dashboard-grid">
        <section className="content-card current-ride-section">
          <div className="section-heading compact">
            <div><span className="eyebrow">CURRENT RIDE</span><h2>Latest status</h2></div>
            {currentRide && <button className="text-button" type="button" onClick={() => handleNavigate('rides')}>View details <i className="bi bi-arrow-right" /></button>}
          </div>
          <RideStatus ride={currentRide} onCancel={handleCancel} onPay={handlePay} actionLoading={actionLoading} />
        </section>

        <section className="content-card service-card">
          <div className="section-heading compact"><div><span className="eyebrow">SERVICE AREAS</span><h2>Six local destinations</h2></div></div>
          <div className="location-list">
            {LOCATIONS.map((location, index) => (
              <div key={location}><span>{String(index + 1).padStart(2, '0')}</span><strong>{location}</strong><i className="bi bi-geo-alt" /></div>
            ))}
          </div>
          <button className="btn btn-outline-navy w-100" type="button" onClick={() => handleNavigate('book')}><i className="bi bi-pin-map" /> Plan a route</button>
        </section>
      </div>

      <Instructions />
    </>
  );

  const bookingPage = () => (
    <form onSubmit={handleBook} className="booking-layout">
      <section className="content-card booking-form-card">
        <div className="section-heading"><div><span className="eyebrow">YOUR ROUTE</span><h2>Where should we pick you up?</h2><p>All locations are part of this local school demonstration.</p></div></div>
        {currentRide && (
          <div className="alert alert-warning"><i className="bi bi-info-circle" /> You already have a {currentRide.status.toLowerCase()} ride. Complete or cancel it before booking another.</div>
        )}
        <div className="route-inputs">
          <div>
            <label htmlFor="pickup">Pickup location</label>
            <div className="select-with-icon"><i className="bi bi-geo-alt" /><select id="pickup" value={booking.pickup} onChange={(event) => setBooking({ ...booking, pickup: event.target.value })}>{LOCATIONS.map((location) => <option key={location}>{location}</option>)}</select></div>
          </div>
          <button className="swap-route" type="button" aria-label="Swap pickup and destination" onClick={() => setBooking({ pickup: booking.destination, destination: booking.pickup })}><i className="bi bi-arrow-down-up" /></button>
          <div>
            <label htmlFor="destination">Destination</label>
            <div className="select-with-icon"><i className="bi bi-flag" /><select id="destination" value={booking.destination} onChange={(event) => setBooking({ ...booking, destination: event.target.value })}>{LOCATIONS.map((location) => <option key={location}>{location}</option>)}</select></div>
          </div>
        </div>
        {booking.pickup === booking.destination && <p className="field-error">Pickup and destination must be different.</p>}
        <MapView pickup={booking.pickup} destination={booking.destination} />
      </section>

      <aside className="booking-review">
        {quoteLoading ? <Loading label="Calculating estimate…" /> : <FareTaxStatus quote={quote} />}
        <div className="content-card review-card">
          <span className="eyebrow">READY TO REQUEST?</span>
          <h3>Review and submit</h3>
          <p>The backend saves your request, selects an available tricycle, and creates a notification.</p>
          <ul>
            <li><i className="bi bi-check2" /> Unique ride identifier</li>
            <li><i className="bi bi-check2" /> Automatic local assignment</li>
            <li><i className="bi bi-check2" /> Persistent ride history</li>
          </ul>
          <button className="btn btn-navy w-100" type="submit" disabled={!quote || quoteLoading || Boolean(currentRide) || actionLoading === 'book'}>
            {actionLoading === 'book' ? <><span className="spinner-border spinner-border-sm" /> Saving request…</> : <><i className="bi bi-send" /> Request Ride</>}
          </button>
        </div>
      </aside>
    </form>
  );

  const ridesPage = () => (
    <>
      <RideStatus ride={currentRide} onCancel={handleCancel} onPay={handlePay} actionLoading={actionLoading} />
      <section className="content-card history-card">
        <div className="section-heading"><div><span className="eyebrow">SAVED RECORDS</span><h2>Ride history</h2><p>Every row is retrieved from the local SQLite database.</p></div><span className="record-count">{rides.length} {rides.length === 1 ? 'record' : 'records'}</span></div>
        {rides.length === 0 ? (
          <div className="empty-state"><span className="empty-icon"><i className="bi bi-clock-history" /></span><h3>No ride history yet</h3><p>Book your first tricycle to create a saved record.</p><button className="btn btn-gold" type="button" onClick={() => handleNavigate('book')}>Book a tricycle</button></div>
        ) : (
          <div className="table-responsive"><table className="table sakay-table"><thead><tr><th>Date</th><th>Route</th><th>Tricycle</th><th>Fare</th><th>Payment</th><th>Status</th></tr></thead><tbody>
            {rides.map((ride) => <tr key={ride.ride_id}><td>{formatRideDate(ride.created_at)}</td><td><strong>{ride.pickup}</strong><span className="table-route">{ride.destination}</span></td><td>{ride.plate_number || '—'}</td><td>₱{Number(ride.fare).toFixed(2)}</td><td>{ride.payment_status}</td><td><span className={`status-badge status-${ride.status.toLowerCase().replace(' ', '-')}`}>{ride.status}</span></td></tr>)}
          </tbody></table></div>
        )}
      </section>
    </>
  );

  const adminOverview = () => (
    <>
      <section className="admin-welcome">
        <div><span className="eyebrow">LOCAL DISPATCH BOARD</span><h2>Good day, {user.fullName}.</h2><p>Review requests and keep simulated tricycle assignments moving.</p></div>
        <button className="btn btn-gold" type="button" onClick={() => handleNavigate('requests')}><i className="bi bi-clipboard2-check" /> Review requests</button>
      </section>
      <section className="stat-grid admin-stats">
        {[
          ['Passengers', stats?.passengers, 'bi-people', 'navy'],
          ['Pending requests', stats?.pendingRides, 'bi-hourglass-split', 'gold'],
          ['Active rides', stats?.activeRides, 'bi-signpost-2', 'green'],
          ['Available tricycles', stats?.availableTricycles, 'bi-truck-front', 'navy'],
        ].map(([label, value, icon, color]) => <div className="stat-card" key={label}><span className={`stat-icon ${color}`}><i className={`bi ${icon}`} /></span><div><strong>{value ?? 0}</strong><span>{label}</span></div></div>)}
      </section>
      <div className="dashboard-grid admin-dashboard-grid">
        <section className="content-card">
          <div className="section-heading compact"><div><span className="eyebrow">RECENT REQUESTS</span><h2>Latest ride activity</h2></div><button className="text-button" type="button" onClick={() => handleNavigate('requests')}>Manage all <i className="bi bi-arrow-right" /></button></div>
          {adminRides.length === 0 ? <div className="empty-state"><span className="empty-icon"><i className="bi bi-clipboard2" /></span><h3>No ride requests yet</h3><p>Passenger requests will appear here automatically.</p></div> : <div className="compact-ride-list">{adminRides.slice(0, 5).map((ride) => <button type="button" key={ride.ride_id} onClick={() => handleNavigate('requests')}><span className="notification-icon"><i className="bi bi-signpost-2" /></span><span><strong>{ride.passenger_name}</strong><small>{ride.pickup} → {ride.destination}</small></span><span className={`status-badge status-${ride.status.toLowerCase().replace(' ', '-')}`}>{ride.status}</span></button>)}</div>}
        </section>
        <section className="content-card">
          <div className="section-heading compact"><div><span className="eyebrow">RIDE BREAKDOWN</span><h2>All saved rides</h2></div></div>
          <div className="breakdown-list">
            <div><span>Completed</span><strong>{stats?.completedRides ?? 0}</strong></div>
            <div><span>Cancelled</span><strong>{stats?.cancelledRides ?? 0}</strong></div>
            <div><span>Total requests</span><strong>{stats?.totalRides ?? 0}</strong></div>
          </div>
          <p className="simulation-note"><i className="bi bi-info-circle" /> Counts are calculated from current database records, not hardcoded.</p>
        </section>
      </div>
    </>
  );

  const requestsPage = () => (
    <section className="content-card requests-card">
      <div className="section-heading">
        <div><span className="eyebrow">DISPATCH MANAGEMENT</span><h2>All ride requests</h2><p>Select a status and, when needed, an available tricycle. Save to persist both.</p></div>
        <select className="form-select status-filter" value={statusFilter} onChange={(event) => setStatusFilter(event.target.value)} aria-label="Filter rides by status"><option value="">All statuses</option>{ALL_STATUSES.map((status) => <option key={status}>{status}</option>)}</select>
      </div>
      {filteredAdminRides.length === 0 ? <div className="empty-state"><span className="empty-icon"><i className="bi bi-clipboard2-check" /></span><h3>No matching requests</h3><p>{statusFilter ? `There are no ${statusFilter.toLowerCase()} rides.` : 'Passenger ride requests will appear here.'}</p></div> : <div className="admin-request-list">{filteredAdminRides.map((ride) => {
        const form = adminForms[ride.ride_id] || {};
        return <form className="admin-request" key={ride.ride_id} onSubmit={(event) => handleAdminUpdate(event, ride)}>
          <div className="request-main">
            <div className="request-id"><span className={`status-badge status-${ride.status.toLowerCase().replace(' ', '-')}`}>{ride.status}</span><small>#{ride.ride_id.slice(0, 8).toUpperCase()}</small></div>
            <h3>{ride.pickup} <i className="bi bi-arrow-right" /> {ride.destination}</h3>
            <p><strong>{ride.passenger_name}</strong> · @{ride.passenger_username} · {formatRideDate(ride.created_at)}</p>
            <div className="request-meta"><span><i className="bi bi-cash" /> ₱{Number(ride.fare).toFixed(2)}</span><span><i className="bi bi-wallet2" /> {ride.payment_status}</span><span><i className="bi bi-truck-front" /> {ride.plate_number || 'Unassigned'}</span></div>
          </div>
          <div className="request-controls">
            <label>Status<select className="form-select form-select-sm" value={form.status || ride.status} onChange={(event) => updateAdminForm(ride.ride_id, 'status', event.target.value)}>{ALL_STATUSES.map((status) => <option key={status}>{status}</option>)}</select></label>
            <label>Tricycle<select className="form-select form-select-sm" value={form.tricycleId || ride.tricycle_id || ''} onChange={(event) => updateAdminForm(ride.ride_id, 'tricycleId', event.target.value)}><option value="">Select tricycle</option>{tricycles.filter((tricycle) => tricycle.status === 'Available' || tricycle.tricycle_id === ride.tricycle_id).map((tricycle) => <option key={tricycle.tricycle_id} value={tricycle.tricycle_id}>{tricycle.plate_number} — {tricycle.driver_name}</option>)}</select></label>
            <button className="btn btn-navy btn-sm" type="submit" disabled={actionLoading === `admin-${ride.ride_id}`}>{actionLoading === `admin-${ride.ride_id}` ? 'Saving…' : <><i className="bi bi-check2" /> Save update</>}</button>
          </div>
        </form>;
      })}</div>}
    </section>
  );

  const passengersPage = () => (
    <section className="content-card">
      <div className="section-heading"><div><span className="eyebrow">USER RECORDS</span><h2>Registered passengers</h2><p>Only passenger accounts are listed; administrator accounts are excluded.</p></div><span className="record-count">{passengers.length} passengers</span></div>
      {passengers.length === 0 ? <div className="empty-state"><span className="empty-icon"><i className="bi bi-people" /></span><h3>No passengers registered</h3><p>Create a passenger account from the sign-in page.</p></div> : <div className="table-responsive"><table className="table sakay-table"><thead><tr><th>Passenger</th><th>Username</th><th>Ride count</th><th>Last ride</th><th>User ID</th></tr></thead><tbody>{passengers.map((passenger) => <tr key={passenger.user_id}><td><span className="table-avatar">{passenger.full_name.charAt(0).toUpperCase()}</span><strong>{passenger.full_name}</strong></td><td>@{passenger.username}</td><td>{passenger.ride_count}</td><td>{passenger.last_ride ? formatRideDate(passenger.last_ride) : 'No rides yet'}</td><td><code>{passenger.user_id.slice(0, 8)}</code></td></tr>)}</tbody></table></div>}
    </section>
  );

  const tricyclesPage = () => (
    <section className="content-card">
      <div className="section-heading"><div><span className="eyebrow">LOCAL FLEET</span><h2>Simulated tricycle availability</h2><p>Assignment changes these records. This is not a real driver dispatch service.</p></div><span className="record-count">{tricycles.filter((item) => item.status === 'Available').length} available</span></div>
      <div className="tricycle-grid">{tricycles.map((tricycle) => <article className="tricycle-card" key={tricycle.tricycle_id}><div className="tricycle-card-top"><span className="tricycle-icon"><i className="bi bi-truck-front" /></span><span className={`fleet-status fleet-${tricycle.status.toLowerCase().replace(' ', '-')}`}>{tricycle.status}</span></div><h3>{tricycle.plate_number}</h3><p>{tricycle.driver_name}</p><small>{tricycle.tricycle_id}</small></article>)}</div>
    </section>
  );

  const renderContent = () => {
    if (activePage === 'book') return bookingPage();
    if (activePage === 'rides') return ridesPage();
    if (activePage === 'notifications') return <Notifications notifications={notifications} onRead={handleRead} onReadAll={handleReadAll} />;
    if (activePage === 'requests') return requestsPage();
    if (activePage === 'passengers') return passengersPage();
    if (activePage === 'tricycles') return tricyclesPage();
    if (activePage === 'admin') return adminOverview();
    return passengerDashboard();
  };

  return (
    <div className="app-shell">
      <Sidebar role={user.role} activePage={activePage} onNavigate={handleNavigate} onLogout={handleLogout} unreadCount={unreadCount} isOpen={sidebarOpen} onClose={() => setSidebarOpen(false)} />
      {sidebarOpen && <button className="sidebar-overlay" type="button" aria-label="Close navigation" onClick={() => setSidebarOpen(false)} />}
      <main className="app-main">
        <header className="app-topbar">
          <button className="mobile-menu" type="button" onClick={() => setSidebarOpen(true)} aria-label="Open navigation"><i className="bi bi-list" /></button>
          <div><h1>{pageTitle}</h1><p>{pageSubtitle}</p></div>
          <div className="topbar-actions">
            <button className="refresh-button" type="button" onClick={() => loadData(false)} aria-label="Refresh data"><i className="bi bi-arrow-clockwise" /></button>
            {!isAdmin && <button className="topbar-bell" type="button" onClick={() => handleNavigate('notifications')} aria-label={`${unreadCount} unread notifications`}><i className="bi bi-bell" />{unreadCount > 0 && <span>{unreadCount}</span>}</button>}
            <button className="user-chip" type="button" onClick={() => navigate('/profile')}><span>{user.fullName?.charAt(0).toUpperCase()}</span><div><strong>{user.fullName}</strong><small>{isAdmin ? 'Administrator' : `@${user.username}`}</small></div></button>
          </div>
        </header>

        <div className="app-content">
          {error && <div className="alert alert-danger alert-dismissible" role="alert"><i className="bi bi-exclamation-circle" /> {error}<button type="button" className="btn-close" onClick={() => setError('')} aria-label="Close" /></div>}
          {notice && <div className="alert alert-success alert-dismissible" role="status"><i className="bi bi-check-circle" /> {notice}<button type="button" className="btn-close" onClick={() => setNotice('')} aria-label="Close" /></div>}
          {loading ? <Loading label={isAdmin ? 'Loading administrator records…' : 'Loading your rides…'} /> : renderContent()}
        </div>
        <footer className="app-footer">Sakay All · Group Three · Local school demonstration · Estimated fares and simulated payments only</footer>
      </main>
    </div>
  );
}

